"""
Utility Functions
=================

Helper functions for prompt formatting and conversation management.
"""


def format_prompt(history: list[dict], tokenizer=None) -> str:
    """
    Format conversation history for Mistral-Instruct.

    Args:
        history: List of dicts with {"role": "user"|"assistant", "content": str}
        tokenizer: Optional tokenizer (reserved for future use)

    Returns:
        Formatted prompt string

    Example:
        >>> history = [
        ...     {"role": "user", "content": "Hello"},
        ...     {"role": "assistant", "content": "Hi there"},
        ...     {"role": "user", "content": "How are you?"}
        ... ]
        >>> format_prompt(history)
        '[INST] Hello [/INST] Hi there</s>[INST] How are you? [/INST]'
    """
    # Mistral uses [INST] ... [/INST] format
    formatted = ""
    for msg in history:
        if msg["role"] == "user":
            formatted += f"[INST] {msg['content']} [/INST]"
        elif msg["role"] == "assistant":
            formatted += f" {msg['content']}</s>"
    return formatted


def format_backroom_turn(previous_response: str, turn: int = None) -> str:
    """
    Format the previous agent's response as input for the next agent.

    This is a simplified version that treats each response as a new user message
    in the backroom conversation.

    Args:
        previous_response: The text generated by the previous agent
        turn: Optional turn number (for debugging/logging)

    Returns:
        Formatted prompt string for next agent
    """
    return f"[INST] {previous_response} [/INST]"


def load_json_with_comments(filepath: str) -> dict:
    """
    Load JSON file, stripping // comments if present.

    Args:
        filepath: Path to JSON file

    Returns:
        Parsed JSON as dict
    """
    import json
    import re

    with open(filepath, 'r') as f:
        content = f.read()

    # Remove // style comments
    content = re.sub(r'//.*$', '', content, flags=re.MULTILINE)

    return json.loads(content)


def estimate_storage_size(num_turns: int, avg_tokens_per_turn: int = 256,
                          vocab_size: int = 32000, save_attention: bool = False) -> dict:
    """
    Estimate storage requirements for a session.

    Args:
        num_turns: Number of conversation turns
        avg_tokens_per_turn: Average tokens generated per turn
        vocab_size: Model vocabulary size
        save_attention: Whether attention weights will be saved

    Returns:
        Dictionary with size estimates in bytes
    """
    # Logits: tokens × vocab_size × 4 bytes (float32)
    logits_per_turn = avg_tokens_per_turn * vocab_size * 4

    # Metrics: compressed derived data (~50KB per turn)
    metrics_per_turn = 50 * 1024

    # Attention: very large (~100MB per turn if saved)
    attention_per_turn = 100 * 1024 * 1024 if save_attention else 0

    # Text: negligible (~2KB per turn)
    text_per_turn = 2 * 1024

    total_per_turn = logits_per_turn + metrics_per_turn + attention_per_turn + text_per_turn
    total_session = total_per_turn * num_turns

    return {
        "logits_per_turn_mb": logits_per_turn / (1024 * 1024),
        "metrics_per_turn_mb": metrics_per_turn / (1024 * 1024),
        "attention_per_turn_mb": attention_per_turn / (1024 * 1024) if save_attention else 0,
        "total_per_turn_mb": total_per_turn / (1024 * 1024),
        "total_session_mb": total_session / (1024 * 1024),
        "total_session_gb": total_session / (1024 * 1024 * 1024)
    }
